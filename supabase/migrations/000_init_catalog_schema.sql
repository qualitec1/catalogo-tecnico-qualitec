-- SQL Schema to initialize the catalog tables in a new Supabase project

-- 1. Create table category_assets
CREATE TABLE IF NOT EXISTS public.category_assets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  category text UNIQUE NOT NULL,
  cover_image_url text,
  cover_image_blob bytea, -- kept for compatibility, will be null for R2 assets
  color_hex text DEFAULT '#005db7',
  created_at timestamp with time zone DEFAULT now()
);

-- Enable RLS for category_assets
ALTER TABLE public.category_assets ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.category_assets FOR SELECT TO public USING (true);
CREATE POLICY "Allow authenticated modifications" ON public.category_assets FOR ALL TO authenticated USING (true);

-- 2. Create table pdf_settings
CREATE TABLE IF NOT EXISTS public.pdf_settings (
